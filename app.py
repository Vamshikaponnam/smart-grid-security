import json
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st
import streamlit.components.v1 as components
import torch
from sklearn.preprocessing import StandardScaler

from model.autoencoder_gan import SmartGridSecurityModel
from utils.data_loader import generate_synthetic_data

st.set_page_config(
    page_title="Smart Grid Security Center",
    page_icon="🛡️",
    layout="wide",
)

# Names used by the trained classifier -> names shown on the dashboard
CLASS_NAMES = {
    0: "Normal",
    1: "DDoS Attack",
    2: "Data Injection",
    3: "Command Injection",
    4: "Scanning",
}


@st.cache_resource
def load_trained_model():
    """Load the existing trained PyTorch checkpoints once per app instance."""
    torch.set_num_threads(1)
    model = SmartGridSecurityModel(device=torch.device("cpu"))
    model.load_model("saved_models/smart_grid_model")
    return model


def create_demo_data(n_samples=500):
    np.random.seed(42)
    raw_df = generate_synthetic_data(
        n_samples=n_samples, time_steps=24, n_features=10, n_classes=5
    )
    feature_columns = raw_df.columns[:-1]
    features = raw_df.loc[:, feature_columns].to_numpy(dtype=np.float32)
    true_labels = raw_df["label"].to_numpy(dtype=int)
    scaler = StandardScaler()
    scaled = scaler.fit_transform(features)
    sequences = scaled.reshape(-1, 24, 10)
    return raw_df, sequences, true_labels


def run_detection(n_samples):
    model = load_trained_model()
    raw_df, sequences, true_labels = create_demo_data(n_samples)
    anomalies, errors, threshold = model.detect_anomalies(sequences)
    probabilities = model.classify_attacks(sequences)
    predicted = np.argmax(probabilities, axis=1)
    results = pd.DataFrame({
        "actual_synthetic_label": [CLASS_NAMES[int(x)] for x in true_labels],
        "predicted_class": [CLASS_NAMES[int(x)] for x in predicted],
        "anomaly_detected": np.asarray(anomalies).astype(bool),
        "reconstruction_error": errors,
        "prediction_confidence": probabilities.max(axis=1),
    })
    return raw_df, results, float(threshold)


# ---------------- Sidebar ----------------
with st.sidebar:
    st.header("Detection settings")
    sample_count = st.selectbox("Number of synthetic records", [200, 500, 1000], index=1)
    rerun = st.button("Run detection again", type="primary")
    st.caption("The model expects 24 time steps × 10 features per record.")

# ---------------- Run the real model ----------------
key = f"results_{sample_count}"
if rerun or key not in st.session_state:
    try:
        with st.spinner("Running the trained AutoEncoder-GAN and classifier..."):
            raw_df, results, threshold = run_detection(sample_count)
            st.session_state[key] = (raw_df, results, threshold)
    except Exception as exc:
        st.error(f"Could not run the model: {exc}")
        st.exception(exc)
        st.stop()

raw_df, results, threshold = st.session_state[key]

counts = results["predicted_class"].value_counts().to_dict()
payload = {
    "counts": {name: int(counts.get(name, 0)) for name in CLASS_NAMES.values()},
    "total": int(len(results)),
    "anomalies": int(results["anomaly_detected"].sum()),
    "threshold": float(threshold),
}

# ---------------- Dashboard (same look as the demo) ----------------
html = Path(__file__).with_name("dashboard.html").read_text(encoding="utf-8")
html = html.replace("/*REAL_DATA*/null", json.dumps(payload))
components.html(html, height=1500, scrolling=True)

# ---------------- Raw results ----------------
with st.expander("Prediction results (from the trained model)"):
    st.dataframe(results.head(100), use_container_width=True)
    st.download_button(
        "Download prediction results (CSV)",
        data=results.to_csv(index=False).encode("utf-8"),
        file_name="smart_grid_detection_results.csv",
        mime="text/csv",
    )

st.caption(
    "Synthetic data is generated by the repository's own generator, so results show the "
    "workflow and are not evidence of performance on real smart-grid traffic."
)
